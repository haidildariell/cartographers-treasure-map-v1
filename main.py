        ("THE VERY POLITE", 700, 392, 22),
        ("VOLCANO", 700, 418, 22),
        ("LAKE SECOND BREAKFAST", 565, 468, 22),
        ("X MARKS THE SPOT", 700, 640, 24),
        ("THE GIGGLING WOODS", 430, 738, 22),
        ("PORT LAST-CHANCE", 290, 648, 24),
        ("THE OLD GIFT SHOPPE", 280, 688, 18),
