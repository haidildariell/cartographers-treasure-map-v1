ADVANCE = 11.0  # glyph advance in grid units
GLYPH_H = 14.0


class Canvas:
    """An RGB bytearray canvas with scanline fills and thick polylines."""

    def __init__(self, w, h, bg):
        self.w, self.h = w, h
        self.buf = bytearray(bytes(bg) * (w * h))

    def _idx(self, x, y):
        return (y * self.w + x) * 3

    def set_px(self, x, y, color):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = self._idx(x, y)
            self.buf[i:i + 3] = bytes(color)

    def blend_px(self, x, y, color, alpha):
        """Alpha-blend a pixel: alpha 0..1."""
        if 0 <= x < self.w and 0 <= y < self.h and alpha > 0:
            i = self._idx(x, y)
            a = alpha
            self.buf[i] = int(self.buf[i] * (1 - a) + color[0] * a)
            self.buf[i + 1] = int(self.buf[i + 1] * (1 - a) + color[1] * a)
            self.buf[i + 2] = int(self.buf[i + 2] * (1 - a) + color[2] * a)

    def fill_rect(self, x0, y0, x1, y1, color):
        x0, y0 = max(0, x0), max(0, y0)
        x1, y1 = min(self.w, x1), min(self.h, y1)
        row = bytes(color) * (x1 - x0)
        for y in range(y0, y1):
            i = self._idx(x0, y)
            self.buf[i:i + len(row)] = row

    def fill_polygon(self, pts, color):
        """Even-odd scanline fill for a simple polygon (float coords ok)."""
        if len(pts) < 3:
            return
        ys = [p[1] for p in pts]
        y0, y1 = max(0, int(math.floor(min(ys)))), min(self.h - 1, int(math.ceil(max(ys))))
        n = len(pts)
        for y in range(y0, y1 + 1):
            yc = y + 0.5
            xs = []
            for i in range(n):
                x1, y1p = pts[i]
                x2, y2p = pts[(i + 1) % n]
                if (y1p <= yc < y2p) or (y2p <= yc < y1p):
                    t = (yc - y1p) / (y2p - y1p)
                    xs.append(x1 + t * (x2 - x1))
            xs.sort()
            for j in range(0, len(xs) - 1, 2):
                xa, xb = int(math.ceil(xs[j])), int(math.floor(xs[j + 1]))
                if xb >= xa:
                    xa = max(0, xa)
                    xb = min(self.w - 1, xb)
                    i = self._idx(xa, y)
                    self.buf[i:i + (xb - xa + 1) * 3] = bytes(color) * (xb - xa + 1)

    def fill_circle(self, cx, cy, r, color):
        r = int(round(r))
        if r <= 0:
            return
        for dy in range(-r, r + 1):
            dx = int(math.sqrt(max(0, r * r - dy * dy)))
            y = int(round(cy)) + dy
            if 0 <= y < self.h:
                xa, xb = int(round(cx)) - dx, int(round(cx)) + dx
                xa, xb = max(0, xa), min(self.w - 1, xb)
                if xb >= xa:
                    i = self._idx(xa, y)
                    self.buf[i:i + (xb - xa + 1) * 3] = bytes(color) * (xb - xa + 1)

    def fill_ellipse(self, cx, cy, rx, ry, color):
        for dy in range(-int(ry), int(ry) + 1):
            t = dy / ry if ry else 0
            dx = int(rx * math.sqrt(max(0.0, 1.0 - t * t)))
            y = int(round(cy)) + dy
            if 0 <= y < self.h:
                xa, xb = int(round(cx)) - dx, int(round(cx)) + dx
                xa, xb = max(0, xa), min(self.w - 1, xb)
                if xb >= xa:
                    i = self._idx(xa, y)
                    self.buf[i:i + (xb - xa + 1) * 3] = bytes(color) * (xb - xa + 1)

    def soft_blob(self, cx, cy, rx, ry, color, alpha):
        """A soft-edged elliptical wash (radial falloff)."""
        x0, y0 = max(0, int(cx - rx)), max(0, int(cy - ry))
        x1, y1 = min(self.w, int(cx + rx) + 1), min(self.h, int(cy + ry) + 1)
        for y in range(y0, y1):
            ny = (y - cy) / ry
            for x in range(x0, x1):
                nx = (x - cx) / rx
                d = nx * nx + ny * ny
                if d < 1.0:
                    self.blend_px(x, y, color, alpha * (1.0 - d) * (1.0 - d))

    def thick_line(self, x1, y1, x2, y2, width, color):
        """A line with round caps, drawn as a quad plus end circles."""
        dx, dy = x2 - x1, y2 - y1
        length = math.hypot(dx, dy)
        if length < 0.001:
            self.fill_circle(x1, y1, width / 2.0, color)
            return
        nx, ny = -dy / length * width / 2.0, dx / length * width / 2.0
        self.fill_polygon([(x1 + nx, y1 + ny), (x2 + nx, y2 + ny),
                           (x2 - nx, y2 - ny), (x1 - nx, y1 - ny)], color)
        self.fill_circle(x1, y1, width / 2.0, color)
        self.fill_circle(x2, y2, width / 2.0, color)

    def polyline(self, pts, width, color, closed=False):
        pts = list(pts)
        if closed and len(pts) > 2:
            pts = pts + [pts[0]]
        for i in range(len(pts) - 1):
            self.thick_line(pts[i][0], pts[i][1], pts[i + 1][0], pts[i + 1][1],
                            width, color)
        # round joins: stamp a circle at every interior joint
        for (x, y) in pts[1:-1]:
            self.fill_circle(x, y, width / 2.0, color)

    def dashed_line(self, x1, y1, x2, y2, width, color, dash=12, gap=9):
        length = math.hypot(x2 - x1, y2 - y1)
        if length < 0.001:
            return
        ux, uy = (x2 - x1) / length, (y2 - y1) / length
        d = 0.0
        while d < length:
            e = min(d + dash, length)
            self.thick_line(x1 + ux * d, y1 + uy * d, x1 + ux * e, y1 + uy * e,
                            width, color)
            d = e + gap

    def arc(self, cx, cy, r, a0, a1, width, color, steps=40):
        pts = []
        for i in range(steps + 1):
            a = a0 + (a1 - a0) * i / steps
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
        self.polyline(pts, width, color)

    def circle_outline(self, cx, cy, r, width, color, steps=72):
        pts = []
        for i in range(steps):
            a = 2 * math.pi * i / steps
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
        self.polyline(pts, width, color, closed=True)


def catmull_rom(points, samples_per_seg=12, closed=True):
    """Smooth a point list into a dense polyline (Catmull-Rom spline)."""
    pts = list(points)
    if closed:
        ext = [pts[-1]] + pts + [pts[0], pts[1]]
    else:
        ext = [pts[0]] + pts + [pts[-1]]
    out = []
    for i in range(len(ext) - 3):
        p0, p1, p2, p3 = ext[i], ext[i + 1], ext[i + 2], ext[i + 3]
        for s in range(samples_per_seg):
            t = s / samples_per_seg
            t2, t3 = t * t, t * t * t
            x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t +
                       (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 +
                       (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
            y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t +
                       (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 +
                       (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
            out.append((x, y))
    if closed:
        out.append(out[0])
    else:
        out.append(pts[-1])
    return out


# ------------------------------------------------------------ text drawing ---
def text_width(text, size):
    """Width in px of `text` rendered at cap-height `size`."""
    return len(text) * ADVANCE * (size / GLYPH_H)


def draw_text(cv, text, x, y, size, color, align="left", stroke=None):
    """Draw all-caps text; (x, y) is the top-left (or anchor by `align`).

    `stroke` is the relative stroke width (fraction of size); default 0.14.
    A halo pass can be done by calling twice: first a thicker light pass.
    """
    text = text.upper()
    scale = size / GLYPH_H
    wdt = stroke if stroke is not None else 0.14 * size
    wdt = max(1.5, wdt)
    if align == "center":
        x -= text_width(text, size) / 2.0
    elif align == "right":
        x -= text_width(text, size)
    cx = x
    for ch in text:
        strokes = FONT.get(ch)
        if strokes is None:
            ch = "?"
            strokes = FONT["?"]
        for stroke_pts in strokes:
            pts = [(cx + px * scale, y + py * scale) for (px, py) in stroke_pts]
            if len(pts) == 1:
                cv.fill_circle(pts[0][0], pts[0][1], wdt * 0.9, color)
            elif len(pts) >= 2:
                cv.polyline(pts, wdt, color)
        cx += ADVANCE * scale
    return cx


def draw_label(cv, text, cx, cy, size, color=INK, halo=PARCHMENT, halo_w=None):
    """A centred map label with a light halo so it reads over any terrain."""
    if halo is not None:
        hw = halo_w if halo_w is not None else 0.30 * size
        draw_text(cv, text, cx, cy - size / 2.0, size, halo, align="center",
                  stroke=hw)
    draw_text(cv, text, cx, cy - size / 2.0, size, color, align="center")


# -------------------------------------------------------------- PNG writer --
def _crc(chunk_type, data):
    return binascii.crc32(chunk_type + data) & 0xFFFFFFFF


def _chunk(chunk_type, data):
    return (struct.pack(">I", len(data)) + chunk_type + data +
            struct.pack(">I", _crc(chunk_type, data)))


def _filter_up(row, prev):
    """Up filter: byte minus the byte above (mod 256), as bytes."""
    return bytes((b - p) & 0xFF for b, p in zip(row, prev))


def write_png(path, cv):
    """Encode the canvas as PNG (filter Up on every row, zlib level 9)."""
    w, h = cv.w, cv.h
    raw = bytearray()
    prev = bytes(w * 3)
    for y in range(h):
        row = bytes(cv.buf[y * w * 3:(y + 1) * w * 3])
        raw.append(2)  # filter type Up
        raw += _filter_up(row, prev)
        prev = row
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    png = (b"\x89PNG\r\n\x1a\n" + _chunk(b"IHDR", ihdr) +
           _chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + _chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)
    return len(png)


