def point_in_poly(x, y, pts):
    inside = False
    n = len(pts)
    for i in range(n):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % n]
        if (y1 > y) != (y2 > y):
            xin = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < xin:
                inside = not inside
    return inside


def draw_wave(cv, x, y, s=1.0, color=INK_SOFT, width=2.5):
    """A little hand-drawn wave squiggle."""
    cv.arc(x, y, 9 * s, math.pi * 1.05, math.pi * 1.95, width, color, steps=10)
    cv.arc(x + 16 * s, y, 9 * s, math.pi * 1.05, math.pi * 1.95, width, color, steps=10)


